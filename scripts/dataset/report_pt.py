def load_dataset(path: Path) -> pd.DataFrame:
    """
    Loads the cleaned Portuguese Aletheia dataset.

    Args:
        path:
            Path to the selected Portuguese CSV file.

    Returns:
        Loaded dataframe.
    """

    logger.info(f"Loading dataset: {path}")

    # Read selected Portuguese dataset generated by dt_cleaning.py
    df = pd.read_csv(path, low_memory=False)

    logger.info(f"Loaded dataframe with shape {df.shape}")

    return df


def normalize_types(df: pd.DataFrame) -> pd.DataFrame:
    """
    Normalizes datetime and numeric columns.

    Args:
        df:
            Input dataframe.

    Returns:
        Dataframe with normalized types.
    """

    logger.info("Normalizing column types.")

    # Parse datetime columns used for temporal analysis
    for col in DATETIME_COLUMNS:
        if col in df.columns:
            df[col] = pd.to_datetime(df[col], errors="coerce")

    # Parse engagement and forwarding metrics as numeric
    for col in NUMERIC_COLUMNS:
        if col in df.columns:
            df[col] = pd.to_numeric(df[col], errors="coerce")

    return df


def add_derived_columns(df: pd.DataFrame) -> pd.DataFrame:
    """
    Adds analysis columns for text, replies, forwards, and network summaries.

    Args:
        df:
            Input dataframe.

    Returns:
        Dataframe with derived columns.
    """

    logger.info("Creating derived columns.")

    # Derive message length metrics for text analysis
    df["text_length"] = (
        df[TEXT_COLUMN]
        .fillna("")
        .astype(str)
        .str.len()
    )

    df["word_count"] = (
        df[TEXT_COLUMN]
        .fillna("")
        .astype(str)
        .str.split()
        .str.len()
    )

    # Mark reply and forwarding status
    df["is_reply"] = df["reply_to"].notna()
    df["is_forwarded"] = df["forward_from"].notna()

    # Extract source channel from reply target when reply_to stores a message ID
    df["reply_to_channel"] = (
        df["reply_to"]
        .astype("string")
        .str.extract(
            f"({CHANNEL_PATTERN})",
            expand=False,
        )
    )

    # Extract forward source channel when forward_from stores a channel hash
    df["forward_from_channel"] = (
        df["forward_from"]
        .astype("string")
        .str.extract(
            f"({CHANNEL_PATTERN})",
            expand=False,
        )
    )

    # Create month column for temporal summaries
    df["month"] = (
        df[DATE_COLUMN]
        .dt.to_period("M")
        .astype(str)
    )

    return df


