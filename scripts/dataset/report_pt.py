def build_report(
    overview: dict,
    missing: pd.DataFrame,
    column_profile: pd.DataFrame,
    numeric_summary: pd.DataFrame,
    network_overview: pd.DataFrame,
    channel_summary: pd.DataFrame,
    user_summary: pd.DataFrame,
    user_channel_edges: pd.DataFrame,
    forward_edges: pd.DataFrame,
    reply_edges: pd.DataFrame,
    plots: dict,
) -> str:
    """
    Builds the markdown report text.

    Args:
        overview:
            Dataset overview metrics.

        missing:
            Missing-value table.

        column_profile:
            Column profile table.

        numeric_summary:
            Numeric summary table.

        network_overview:
            Network-level overview table.

        channel_summary:
            Channel-level summary.

        user_summary:
            User-level summary.

        user_channel_edges:
            User-channel edge table.

        forward_edges:
            Forwarding edge table.

        reply_edges:
            Reply edge table.

        plots:
            Plot path mapping.

    Returns:
        Markdown report as string.
    """

    logger.info("Building markdown report.")

    # Prepare overview table for markdown rendering
    overview_table = pd.DataFrame(
        [
            {
                "Metric": key,
                "Value": value,
            }
            for key, value in overview.items()
        ]
    )

    # Accumulate markdown lines in report order
    lines = []

    lines.append("# Aletheia Portuguese Dataset Network Report")
    lines.append("")
    lines.append(
        "Generated automatically from the cleaned Portuguese Aletheia dataset."
    )
    lines.append("")
    lines.append("## Dataset Context")
    lines.append("")
    lines.append(
        "This report focuses on the Portuguese subset of the Aletheia Telegram "
        "dataset. The selected data keep message identifiers, user identifiers, "
        "channel identifiers, message text, timestamps, reply links, forwarding "
        "metadata, and engagement metrics. The emphasis is on communication volume, "
        "channel/user activity, forwarding structure, reply structure, and engagement."
    )
    lines.append("")

    lines.append("## Dataset Overview")
    lines.append("")
    lines.append(md_table(overview_table))
    lines.append("")

    lines.append("## Column Profile")
    lines.append("")
    lines.append(md_table(column_profile, max_rows=40))
    lines.append("")

    lines.append("## Missing Values")
    lines.append("")
    lines.append(
        "Missingness is expected in optional Telegram fields such as replies, "
        "forwarding metadata, and view counts."
    )
    lines.append("")
    lines.append(md_table(missing))
    lines.append("")

    lines.append("## Numeric Summary")
    lines.append("")
    lines.append(md_table(numeric_summary))
    lines.append("")

    # Add temporal activity section and plot when available
    lines.append("## Temporal Activity")
    lines.append("")
    if "messages_over_time" in plots:
        lines.append(
            md_image(
                plots["messages_over_time"],
                "Portuguese messages over time",
            )
        )
    lines.append("")

    lines.append("## Network Overview")
    lines.append("")
    lines.append(md_table(network_overview))
    lines.append("")

    # Add channel-level summaries and relationship plots
    lines.append("## Channel Activity")
    lines.append("")
    if "top_channels" in plots:
        lines.append(
            md_image(
                plots["top_channels"],
                "Top channels by message count",
            )
        )
        lines.append("")
    if "channel_messages_vs_users" in plots:
        lines.append(
            md_image(
                plots["channel_messages_vs_users"],
                "Channel message volume vs unique users",
            )
        )
        lines.append("")
    if "channel_messages_vs_views" in plots:
        lines.append(
            md_image(
                plots["channel_messages_vs_views"],
                "Channel message volume vs total views",
            )
        )
        lines.append("")
    lines.append("### Top Channels")
    lines.append("")
    lines.append(md_table(channel_summary, max_rows=25))
    lines.append("")

    # Add user-level summaries and ranking plot
    lines.append("## User Activity")
    lines.append("")
    if "top_users" in plots:
        lines.append(
            md_image(
                plots["top_users"],
                "Top users by message count",
            )
        )
        lines.append("")
    lines.append("### Top Users")
    lines.append("")
    lines.append(md_table(user_summary, max_rows=25))
    lines.append("")

    lines.append("## User-Channel Network")
    lines.append("")
    lines.append(
        "Each user-channel edge represents posting activity by one user in one channel. "
        "The edge weight is the number of messages posted by that user in that channel."
    )
    lines.append("")
    if "user_channel_edge_weights" in plots:
        lines.append(
            md_image(
                plots["user_channel_edge_weights"],
                "User-channel edge weight distribution",
            )
        )
        lines.append("")
    lines.append("### Strongest User-Channel Edges")
    lines.append("")
    lines.append(md_table(user_channel_edges, max_rows=25))
    lines.append("")

    # Add forwarding network details and figures
    lines.append("## Forwarding Network")
    lines.append("")
    lines.append(
        "Forwarding edges are directed from the original forwarded source channel "
        "to the channel where the selected Portuguese message appears."
    )
    lines.append("")
    if "top_forward_sources" in plots:
        lines.append(
            md_image(
                plots["top_forward_sources"],
                "Top forwarded-from source channels",
            )
        )
        lines.append("")
    if "top_forward_edges" in plots:
        lines.append(
            md_image(
                plots["top_forward_edges"],
                "Top forwarding edges",
            )
        )
        lines.append("")
    lines.append("### Top Forwarding Edges")
    lines.append("")
    lines.append(md_table(forward_edges, max_rows=25))
    lines.append("")

    # Add reply network details and figures
    lines.append("## Reply Network")
    lines.append("")
    lines.append(
        "Reply edges are directed from the replied-to channel to the replying channel, "
        "when the replied-to message ID contains a recoverable channel hash."
    )
    lines.append("")
    if "top_reply_edges" in plots:
        lines.append(
            md_image(
                plots["top_reply_edges"],
                "Top reply edges",
            )
        )
        lines.append("")
    lines.append("### Top Reply Edges")
    lines.append("")
    lines.append(md_table(reply_edges, max_rows=25))
    lines.append("")

    # Add engagement distribution plots
    lines.append("## Engagement Distributions")
    lines.append("")
    if "views_distribution" in plots:
        lines.append(
            md_image(
                plots["views_distribution"],
                "Views distribution",
            )
        )
        lines.append("")
    if "forwards_distribution" in plots:
        lines.append(
            md_image(
                plots["forwards_distribution"],
                "Forwards distribution",
            )
        )
        lines.append("")
    if "reactions_distribution" in plots:
        lines.append(
            md_image(
                plots["reactions_distribution"],
                "Reactions distribution",
            )
        )
        lines.append("")

    # Add text-size distribution plots
    lines.append("## Text Length")
    lines.append("")
    if "text_length_distribution" in plots:
        lines.append(
            md_image(
                plots["text_length_distribution"],
                "Text length distribution",
            )
        )
        lines.append("")
    if "word_count_distribution" in plots:
        lines.append(
            md_image(
                plots["word_count_distribution"],
                "Word count distribution",
            )
        )
        lines.append("")

    return "\n".join(lines)


