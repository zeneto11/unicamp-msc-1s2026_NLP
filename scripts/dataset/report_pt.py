def compute_overview(df: pd.DataFrame) -> dict:
    """
    Computes high-level metrics for the Portuguese selected dataset.

    Args:
        df:
            Input dataframe.

    Returns:
        Dictionary with overview metrics.
    """

    logger.info("Computing overview metrics.")

    # Build the core report metrics
    overview = {
        "Rows": len(df),
        "Columns": len(df.columns),
        "Duplicate message IDs": df["message_id"].duplicated().sum(),
        "Unique channels": df["channel_id"].nunique(),
        "Unique users": df["user_id"].nunique(),
        "Date start": df[DATE_COLUMN].min(),
        "Date end": df[DATE_COLUMN].max(),
        "Messages with replies": int(df["is_reply"].sum()),
        "Messages forwarded from known source": int(df["is_forwarded"].sum()),
        "Known forward source channels": df["forward_from_channel"].nunique(),
        "Known reply source channels": df["reply_to_channel"].nunique(),
        "Total views": df["views"].sum(skipna=True),
        "Total forwards": df["n_forwards"].sum(skipna=True),
        "Total reactions": df["reactions"].sum(skipna=True),
        "Median text length": df["text_length"].median(),
        "Median word count": df["word_count"].median(),
    }

    return overview


def build_missing_table(df: pd.DataFrame) -> pd.DataFrame:
    """
    Builds missing-value summary table.

    Args:
        df:
            Input dataframe.

    Returns:
        Missing-value dataframe.
    """

    logger.info("Computing missing-value table.")

    # Count missing values and percentages for all columns
    missing = (
        df.isna()
        .sum()
        .rename("missing")
        .to_frame()
    )

    missing["missing_pct"] = (
        missing["missing"] / len(df) * 100
    )

    missing["dtype"] = df.dtypes.astype(str)

    missing = (
        missing
        .sort_values(
            "missing",
            ascending=False,
        )
        .reset_index()
        .rename(
            columns={
                "index": "column",
            }
        )
    )

    return missing


def build_column_profile(df: pd.DataFrame) -> pd.DataFrame:
    """
    Builds a compact profile for selected dataset columns.

    Args:
        df:
            Input dataframe.

    Returns:
        Column profile dataframe.
    """

    logger.info("Computing column profile.")

    rows = []

    # Collect dtype, missingness, uniqueness, and top values
    for col in df.columns:
        series = df[col]

        top_value = None
        top_count = None

        value_counts = series.value_counts(
            dropna=True,
        )

        if not value_counts.empty:
            top_value = str(value_counts.index[0])[:90]
            top_count = int(value_counts.iloc[0])

        rows.append(
            {
                "column": col,
                "description": COLUMN_DESCRIPTIONS.get(col, ""),
                "dtype": str(series.dtype),
                "missing": int(series.isna().sum()),
                "missing_pct": round(series.isna().mean() * 100, 2),
                "unique": int(series.nunique(dropna=True)),
                "top_value": top_value,
                "top_count": top_count,
            }
        )

    return pd.DataFrame(rows)


def build_numeric_summary(df: pd.DataFrame) -> pd.DataFrame:
    """
    Builds numeric summary for engagement and forwarding metrics.

    Args:
        df:
            Input dataframe.

    Returns:
        Numeric summary dataframe.
    """

    logger.info("Computing numeric summary.")

    numeric_cols = [
        col for col in NUMERIC_COLUMNS
        if col in df.columns
    ]

    if not numeric_cols:
        return pd.DataFrame()

    summary = (
        df[numeric_cols]
        .describe()
        .T
        .reset_index()
        .rename(
            columns={
                "index": "column",
            }
        )
    )

    return summary


