def report_image_path(filename: str) -> str:
    """
    Builds markdown-relative path for a figure.

    Args:
        filename:
            Figure filename.

    Returns:
        Relative path from the report file.
    """

    # Match figure paths to the markdown report location
    return str(Path("figures") / "pt_report" / filename)


def save_bar_plot(
    series: pd.Series,
    title: str,
    xlabel: str,
    ylabel: str,
    filename: str,
    top_n: int = 20,
) -> str:
    """
    Saves a horizontal bar plot.

    Args:
        series:
            Series to plot.

        title:
            Plot title.

        xlabel:
            X-axis label.

        ylabel:
            Y-axis label.

        filename:
            Output filename.

        top_n:
            Number of top values.

    Returns:
        Relative figure path.
    """

    logger.info(f"Creating plot: {filename}")

    # Count top categories and sort for horizontal readability
    counts = (
        series
        .dropna()
        .astype(str)
        .value_counts()
        .head(top_n)
        .sort_values()
    )

    fig_path = Path(FIGURES_DIR) / filename

    # Render and save the horizontal bar chart
    plt.figure(figsize=(10, 6))
    counts.plot(kind="barh")

    plt.title(title)
    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.tight_layout()
    plt.savefig(fig_path, dpi=150)
    plt.close()

    return report_image_path(filename)


def save_hist_plot(
    series: pd.Series,
    title: str,
    xlabel: str,
    ylabel: str,
    filename: str,
    log_transform: bool = False,
    bins: int = 50,
) -> str:
    """
    Saves a histogram plot.

    Args:
        series:
            Numeric series to plot.

        title:
            Plot title.

        xlabel:
            X-axis label.

        ylabel:
            Y-axis label.

        filename:
            Output filename.

        log_transform:
            Whether to use log1p transform.

        bins:
            Histogram bins.

    Returns:
        Relative figure path.
    """

    logger.info(f"Creating plot: {filename}")

    # Convert values to numeric and drop missing entries before plotting
    values = pd.to_numeric(series, errors="coerce").dropna()

    if log_transform:
        values = np.log1p(values)
        xlabel = f"log1p({xlabel})"

    fig_path = Path(FIGURES_DIR) / filename

    # Render and save the histogram
    plt.figure(figsize=(10, 6))
    plt.hist(values, bins=bins)

    plt.title(title)
    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.tight_layout()
    plt.savefig(fig_path, dpi=150)
    plt.close()

    return report_image_path(filename)


