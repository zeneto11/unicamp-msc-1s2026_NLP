def save_scatter_plot(
    df: pd.DataFrame,
    x: str,
    y: str,
    title: str,
    xlabel: str,
    ylabel: str,
    filename: str,
    log_x: bool = False,
    log_y: bool = False,
) -> str:
    """
    Saves a scatter plot.

    Args:
        df:
            Input dataframe.

        x:
            X-axis column.

        y:
            Y-axis column.

        title:
            Plot title.

        xlabel:
            X-axis label.

        ylabel:
            Y-axis label.

        filename:
            Output filename.

        log_x:
            Whether to log-transform X.

        log_y:
            Whether to log-transform Y.

    Returns:
        Relative figure path.
    """

    logger.info(f"Creating plot: {filename}")

    # Coerce selected columns and remove invalid rows
    plot_df = df[[x, y]].copy()

    plot_df[x] = pd.to_numeric(plot_df[x], errors="coerce")
    plot_df[y] = pd.to_numeric(plot_df[y], errors="coerce")

    plot_df = plot_df.dropna()

    if log_x:
        plot_df[x] = np.log1p(plot_df[x])
        xlabel = f"log1p({xlabel})"

    if log_y:
        plot_df[y] = np.log1p(plot_df[y])
        ylabel = f"log1p({ylabel})"

    fig_path = Path(FIGURES_DIR) / filename

    # Render and save the scatter plot
    plt.figure(figsize=(10, 6))
    plt.scatter(plot_df[x], plot_df[y], alpha=0.5)

    plt.title(title)
    plt.xlabel(xlabel)
    plt.ylabel(ylabel)
    plt.tight_layout()
    plt.savefig(fig_path, dpi=150)
    plt.close()

    return report_image_path(filename)


