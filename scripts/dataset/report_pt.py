# Markdown helpers
# ------------------------------------------------------------

def md_table(
    df: pd.DataFrame,
    max_rows: int = 30,
) -> str:
    """
    Converts dataframe to markdown table.

    Args:
        df:
            Dataframe to convert.

        max_rows:
            Maximum number of rows.

    Returns:
        Markdown table string.
    """

    # Return a placeholder if the table has no rows
    if df is None or df.empty:
        return "_No data available._"

    return (
        df.head(max_rows)
        .to_markdown(index=False)
    )


def md_image(
    path: str,
    caption: str,
) -> str:
    """
    Builds a markdown image reference.

    Args:
        path:
            Relative figure path.

        caption:
            Figure caption.

    Returns:
        Markdown image string.
    """

    # Use standard markdown syntax for embedded figures
    return f"![{caption}]({path})"


